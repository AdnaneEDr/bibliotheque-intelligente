def oracle_ddl(sql):
    """Convert every SQL type token, including types followed by ')' or ','."""
    sql = sql.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    sql = re.sub(r'\bTEXT\b', 'CLOB', sql)
    sql = re.sub(r'\bINTEGER\b', 'NUMBER', sql)
    return re.sub(r'\bVARCHAR\b', 'VARCHAR2', sql)

class Tx:
    def __init__(self, connection, oracle=False):
        self.connection, self.oracle = connection, oracle

    def execute(self, sql, params=None):
        cursor = self.connection.cursor()
        cursor.execute(sql, params or {})
        return cursor

    def rows(self, sql, params=None):
        cursor = self.execute(sql, params)
        names = [x[0].lower() for x in cursor.description]
        output = []
        for values in cursor.fetchall():
            output.append(dict(zip(names, [v.read() if hasattr(v, 'read') else v for v in values])))
        cursor.close()
        return output

    def one(self, sql, params=None):
        rows = self.rows(sql, params)
        return rows[0] if rows else None

    def insert(self, table, **values):
        columns = ', '.join(values)
        binds = ', '.join(':'+key for key in values)
        sql = f'INSERT INTO {table} ({columns}) VALUES ({binds})'
        if self.oracle:
            cursor = self.connection.cursor()
            output = cursor.var(int)
            cursor.execute(sql+' RETURNING id INTO :new_id', {**values, 'new_id': output})
            result = int(output.getvalue()[0])
            cursor.close()
            return result
        cursor = self.execute(sql, values)
        result = cursor.lastrowid
        cursor.close()
        return result

    def lock(self, table, identifier):
        suffix = ' FOR UPDATE' if self.oracle else ''
        return self.one(f'SELECT * FROM {table} WHERE id=:id'+suffix, {'id': identifier})

class Database:
    def __init__(self, settings):
        self.settings = settings
        settings.data_dir.mkdir(parents=True, exist_ok=True)
        self.lock = threading.RLock()
        self.initialize()

    def connect(self):
        if self.settings.db_backend == 'oracle':
            if not self.settings.oracle_user or not self.settings.oracle_password:
                raise RuntimeError('Compte Oracle non configuré. Exécuter scripts/setup_oracle.ps1 dans PowerShell sur le poste Oracle.')
            import oracledb
            return oracledb.connect(user=self.settings.oracle_user, password=self.settings.oracle_password, dsn=self.settings.oracle_dsn)
        conn = sqlite3.connect(self.settings.data_dir/'library.sqlite3', timeout=30)
        conn.execute('PRAGMA foreign_keys=ON')
        conn.execute('PRAGMA journal_mode=WAL')
        return conn

    @contextmanager
    def transaction(self):
        with self.lock:
            conn = self.connect()
            try:
                if self.settings.db_backend == 'sqlite':
                    conn.execute('BEGIN IMMEDIATE')
                yield Tx(conn, self.settings.db_backend == 'oracle')
                conn.commit()
            except Exception:
                conn.rollback()
                raise
            finally:
                conn.close()

    def initialize(self):
        with self.transaction() as tx:
            for sql in SCHEMA:
                if tx.oracle:
                    sql = oracle_ddl(sql)
                else:
                    sql = sql.replace('CREATE TABLE ', 'CREATE TABLE IF NOT EXISTS ').replace('CREATE INDEX ', 'CREATE INDEX IF NOT EXISTS ')
                try:
                    tx.execute(sql).close()
                except Exception as exc:
                    # ORA-00955 means this object already exists. Other DDL errors remain fatal.
                    if not tx.oracle or getattr(exc.args[0], 'code', None) != 955:
                        raise

