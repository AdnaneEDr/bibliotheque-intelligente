import re
import unittest
from backend.db import SCHEMA, oracle_ddl

class OracleSchemaTests(unittest.TestCase):
    def test_no_sqlite_types_remain_in_any_statement(self):
        for statement in SCHEMA:
            with self.subTest(statement=statement):
                converted=oracle_ddl(statement)
                self.assertIsNone(re.search(r'\b(TEXT|AUTOINCREMENT|VARCHAR|INTEGER)\b',converted))
                self.assertEqual(converted.count('('),converted.count(')'))

    def test_nullable_text_at_end_of_table_becomes_clob(self):
        books=next(sql for sql in SCHEMA if sql.startswith('CREATE TABLE books '))
        self.assertIn('description CLOB)',oracle_ddl(books))
        self.assertIn('NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',oracle_ddl(books))

if __name__=='__main__':unittest.main()
